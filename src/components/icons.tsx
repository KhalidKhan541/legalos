import * as React from 'react';

export interface IconProps extends Omit<React.SVGProps<SVGSVGElement>, 'children'> {
  /** Rendered size in px (CSS classes like `h-4 w-4` still win). */
  size?: number | string;
  /** Stroke width — thinner (1.5) reads better at 16px, default 2 at 24px. */
  strokeWidth?: number | string;
}

/**
 * Factory for the inline legal icon set. Every icon is a 24×24 stroke
 * drawing that inherits `currentColor`, so it can be recoloured with text
 * utilities or an explicit `stroke` override.
 */
function makeIcon(displayName: string, children: React.ReactNode) {
  const Icon = React.forwardRef<SVGSVGElement, IconProps>(
    ({ size = 24, strokeWidth = 2, className, ...props }, ref) => (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        aria-hidden="true"
        focusable="false"
        {...props}
      >
        {children}
      </svg>
    )
  );
  Icon.displayName = displayName;
  return Icon;
}

